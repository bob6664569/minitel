/** A four-pointed twinkle, 3x3 sub-pixels. */
const TWINKLE = ['.#.', '###', '.#.'];

/**
 * Seeded star field as pixel-art lines (`width` x `height` sub-pixels):
 * single dots in white or yellow and a few twinkles, away from the
 * rectangles listed in `avoid` ({ x, y, w, h } in sub-pixels).
 */
export function starfield(seed, width, height, { count = 24, twinkles = 3, avoid = [] } = {}) {
  let a = seed >>> 0 || 1;
  const r = () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const rows = Array.from({ length: height }, () => new Array(width).fill('.'));
  const placed = [];
  const free = (x, y, m = 1, gap = 2) => !avoid.some((z) => x >= z.x - m && x < z.x + z.w + m && y >= z.y - m && y < z.y + z.h + m)
    && !placed.some(([px, py, pr]) => Math.abs(px - x) <= pr + gap && Math.abs(py - y) <= pr + gap);
  // One ink colour per cell (2x3 sub-pixels): remember what each cell got.
  const cellInk = new Map();
  const put = (x, y, c) => {
    if (x < 0 || y < 0 || x >= width || y >= height) return false;
    const key = `${x >> 1},${Math.floor(y / 3)}`;
    if (cellInk.has(key) && cellInk.get(key) !== c) return false;
    cellInk.set(key, c);
    rows[y][x] = c;
    return true;
  };
  for (let i = 0, tries = 0; i < twinkles && tries < 200; tries++) {
    const x = 1 + Math.floor(r() * (width - 2));
    const y = 1 + Math.floor(r() * (height - 2));
    if (!free(x, y, 2, 3)) continue;
    const c = r() < 0.5 ? 'y' : 'w';
    TWINKLE.forEach((line, j) => [...line].forEach((ch, k) => { if (ch === '#') put(x + k - 1, y + j - 1, c); }));
    placed.push([x, y, 1]);
    i++;
  }
  for (let i = 0, tries = 0; i < count && tries < 500; tries++) {
    const x = Math.floor(r() * width);
    const y = Math.floor(r() * height);
    if (!free(x, y, 1, 1) || rows[y][x] !== '.') continue;
    if (put(x, y, r() < 0.3 ? 'y' : 'w')) {
      placed.push([x, y, 0]);
      i++;
    }
  }
  return rows.map((row) => row.join(''));
}
