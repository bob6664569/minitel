/**
 * Minitel 8x10 bitmap font — the single source of truth for every renderer.
 *
 * The canvas terminal draws these bitmaps directly, and `tools/build-font.mjs`
 * turns the very same data into the TrueType/WOFF2 web fonts used by the CSS
 * design system. Glyphs are designed in the spirit of the EF9345 character
 * generator used by the Minitel: 8x10 cells, 5x7 capitals, 2-row descenders.
 *
 * Cell anatomy (rows top to bottom):
 *   r0      accents / breathing room
 *   r1..r7  capitals (baseline under r7), ascenders
 *   r3..r7  lowercase x-height
 *   r8..r9  descenders
 *
 * Each glyph is a Uint8Array(10); bit 7 of a row is the leftmost pixel.
 */

export const CELL_WIDTH = 8;
export const CELL_HEIGHT = 10;
/** Pixel rows above the baseline. */
export const ASCENT = 8;
/** Pixel rows below the baseline. */
export const DESCENT = 2;

const glyphs = new Map();

/**
 * Parse a glyph sheet: a header of N characters followed by 10 rows of N
 * space-separated blocks. 5-wide blocks are placed on columns 1..5 of the
 * cell, 8-wide blocks fill the whole cell.
 */
function sheet(width, chars, text, target = glyphs) {
  const labels = [...chars];
  const lines = text.split('\n').map((line) => line.trim()).filter(Boolean);
  if (lines.length !== CELL_HEIGHT) {
    throw new Error(`Glyph sheet "${chars}": expected ${CELL_HEIGHT} rows, got ${lines.length}`);
  }
  const out = labels.map(() => new Uint8Array(CELL_HEIGHT));
  const x0 = width === 8 ? 0 : 1;
  lines.forEach((line, y) => {
    const blocks = line.split(/\s+/);
    if (blocks.length !== labels.length) {
      throw new Error(`Glyph sheet "${chars}", row ${y}: expected ${labels.length} blocks, got ${blocks.length}`);
    }
    blocks.forEach((block, i) => {
      if (block.length !== width) {
        throw new Error(`Glyph sheet "${chars}", row ${y}, glyph "${labels[i]}": expected width ${width}`);
      }
      for (let x = 0; x < width; x++) {
        if (block[x] === '#') out[i][y] |= 0x80 >> (x0 + x);
      }
    });
  });
  labels.forEach((ch, i) => target.set(ch, out[i]));
}

