/** Diacritic marks, as [row, pattern] pairs on columns 1..5. */
const MARKS = {
  grave: [[0, '.#...'], [1, '..#..']],
  acute: [[0, '...#.'], [1, '..#..']],
  circumflex: [[0, '..#..'], [1, '.#.#.']],
  diaeresis: [[1, '.#.#.']],
  tilde: [[0, '.##.#'], [1, '#..#.']],
  cedilla: [[8, '..#..'], [9, '.##..']],
};

function withMark(base, mark) {
  const rows = Uint8Array.from(base);
  for (const [row, pattern] of MARKS[mark]) {
    for (let x = 0; x < 5; x++) if (pattern[x] === '#') rows[row] |= 0x80 >> (1 + x);
  }
  return rows;
}

