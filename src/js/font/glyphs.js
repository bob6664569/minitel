/** Fallback drawn for characters the font does not cover. */
export const NOTDEF = Uint8Array.from([0, 0b01111100, 0b01000100, 0b01000100, 0b01000100, 0b01000100, 0b01000100, 0b01111100, 0, 0]);

/** Read-only view of every glyph, keyed by Unicode character. */
export const glyphMap = glyphs;

/** Bitmap for a character, or `undefined` when the font lacks it. */
export function getGlyph(ch) {
  return glyphs.get(ch);
}

/** Pixel lookup helper: is (x, y) lit in `rows`? */
export function pixel(rows, x, y) {
  return (rows[y] & (0x80 >> x)) !== 0;
}
